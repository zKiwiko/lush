use std::fs::File;
use std::io::Write;

#[derive(Clone, Debug, PartialEq)]
pub enum BuildSystem {
    Raw, // Direct compiler invocation
    CMake,
    Ninja,
}

impl BuildSystem {
    pub fn from_string(s: &str) -> Option<Self> {
        match s.to_lowercase().as_str() {
            "cmake" => Some(BuildSystem::CMake),
            "ninja" => Some(BuildSystem::Ninja),
            "raw" | "none" | "" => Some(BuildSystem::Raw),
            _ => None,
        }
    }

    pub fn as_str(&self) -> &str {
        match self {
            BuildSystem::Raw => "raw",
            BuildSystem::CMake => "cmake",
            BuildSystem::Ninja => "ninja",
        }
    }
}

pub struct GeneratorConfig {
    pub language: String,
    pub files: Vec<String>,
    pub includes: Vec<String>,
    pub lib_paths: Vec<String>,
    pub defines: Vec<String>,
    pub link_libs: Vec<String>,
    pub flags: Vec<String>,
    pub optimize: Option<String>,
    pub debug: bool,
    pub output_name: String,
    pub frameworks: Vec<String>, // For Objective-C
}

/// Generate CMakeLists.txt from builder configuration
pub fn generate_cmake(config: &GeneratorConfig) -> std::io::Result<()> {
    let mut file = File::create("CMakeLists.txt")?;

    let mut content = String::from("cmake_minimum_required(VERSION 3.10)\n");
    content.push_str(&format!("project({})\n\n", config.output_name));

    // Set output directories for clean builds
    content.push_str("set(CMAKE_RUNTIME_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/build)\n");
    content.push_str("set(CMAKE_LIBRARY_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/build)\n");
    content.push_str("set(CMAKE_ARCHIVE_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/build)\n\n");

    // Language setup
    match config.language.as_str() {
        "c" => content.push_str("enable_language(C)\n"),
        "cpp" | "c++" => content.push_str("enable_language(CXX)\n"),
        "objc" => content.push_str("enable_language(OBJC)\n"),
        _ => {}
    }

    // Include directories
    for inc in &config.includes {
        content.push_str(&format!("include_directories({})\n", inc));
    }

    // Compiler definitions
    for define in &config.defines {
        content.push_str(&format!("add_compile_definitions({})\n", define));
    }

    // Compiler flags
    for flag in &config.flags {
        content.push_str(&format!("add_compile_options({})\n", flag));
    }

    if config.debug {
        content.push_str("add_compile_options(-g)\n");
    }

    if let Some(opt) = &config.optimize {
        content.push_str(&format!("add_compile_options(-{})\n", opt));
    }

    // Executable target
    let file_list = config.files.join(" ");
    content.push_str(&format!(
        "\nadd_executable({} {})\n",
        config.output_name, file_list
    ));

    // Link libraries
    for lib in &config.link_libs {
        content.push_str(&format!(
            "target_link_libraries({} {})\n",
            config.output_name, lib
        ));
    }

    // Objective-C frameworks
    for framework in &config.frameworks {
        content.push_str(&format!(
            "find_library(FRAMEWORK_{} NAMES {} TYPE FRAMEWORK)\n",
            framework.to_uppercase(),
            framework
        ));
        content.push_str(&format!(
            "target_link_libraries({} ${{FRAMEWORK_{}}})\n",
            config.output_name,
            framework.to_uppercase()
        ));
    }

    file.write_all(content.as_bytes())?;
    Ok(())
}

/// Generate build.ninja file from builder configuration
pub fn generate_ninja(config: &GeneratorConfig) -> std::io::Result<()> {
    let mut file = File::create("build.ninja")?;

    let mut content = String::from("# Ninja build file - auto-generated by lush\n");
    content.push_str("# Edit at your own risk\n\n");

    // Get the compiler command based on language
    let compiler_cmd = match config.language.as_str() {
        "c" => "gcc",
        "cpp" | "c++" => "g++",
        "objc" => "gcc",
        _ => "gcc",
    };

    // Build compiler flags
    let mut compiler_flags = Vec::new();

    // Optimization
    if let Some(opt) = &config.optimize {
        compiler_flags.push(format!("-{}", opt));
    }

    // Debug symbols
    if config.debug {
        compiler_flags.push("-g".to_string());
    }

    // Include directories
    for inc in &config.includes {
        compiler_flags.push(format!("-I{}", inc));
    }

    // Defines
    for define in &config.defines {
        compiler_flags.push(format!("-D{}", define));
    }

    // Custom flags
    for flag in &config.flags {
        compiler_flags.push(flag.clone());
    }

    let flags_str = compiler_flags.join(" ");

    // Write variables
    content.push_str(&format!("cc = {}\n", compiler_cmd));
    content.push_str(&format!("cflags = {}\n", flags_str));
    content.push_str("builddir = build\n");
    content.push_str("\n");

    // Build rules for each object file
    content.push_str("rule cc\n");
    content.push_str("  command = $cc $cflags -c $in -o $out\n");
    content.push_str("  description = CC $out\n");
    content.push_str("\n");

    // Link rule
    content.push_str("rule link\n");
    content.push_str("  command = $cc $in");

    // Add library paths as flags
    for lib_path in &config.lib_paths {
        content.push_str(&format!(" -L{}", lib_path));
    }

    // Add libraries
    for lib in &config.link_libs {
        content.push_str(&format!(" -l{}", lib));
    }

    // Objective-C frameworks
    for framework in &config.frameworks {
        content.push_str(&format!(" -framework {}", framework));
    }

    content.push_str(&format!(" -o $out\n"));
    content.push_str("  description = LINK $out\n");
    content.push_str("\n");

    // Build object files and link - all in builddir
    let mut object_files = Vec::new();
    for (i, file) in config.files.iter().enumerate() {
        let obj_name = format!("$builddir/{}.o", i);
        object_files.push(obj_name.clone());
        content.push_str(&format!("build {}: cc {}\n", obj_name, file));
    }

    // Final executable in builddir
    let output_path = format!("$builddir/{}", config.output_name);
    content.push_str(&format!(
        "build {}: link {}\n",
        output_path,
        object_files.join(" ")
    ));
    content.push_str(&format!("default {}\n", output_path));

    file.write_all(content.as_bytes())?;
    Ok(())
}

/// Execute CMake build
pub fn execute_cmake(output_name: &str) -> std::io::Result<()> {
    // Create build directory
    std::fs::create_dir_all("build")?;

    // Configure cmake in the build directory
    let status = std::process::Command::new("cmake")
        .args(&["-S", ".", "-B", "build"])
        .status()?;

    if !status.success() {
        return Err(std::io::Error::new(
            std::io::ErrorKind::Other,
            "CMake configuration failed",
        ));
    }

    // Build the project
    let status = std::process::Command::new("cmake")
        .args(&["--build", "build", "--target", output_name])
        .status()?;

    if status.success() {
        Ok(())
    } else {
        Err(std::io::Error::new(
            std::io::ErrorKind::Other,
            "CMake build failed",
        ))
    }
}

/// Execute Ninja build
pub fn execute_ninja(_output_name: &str) -> std::io::Result<()> {
    // Create build directory for output files
    std::fs::create_dir_all("build")?;

    // Run ninja (uses build.ninja in current directory)
    let status = std::process::Command::new("ninja").status()?;

    if status.success() {
        Ok(())
    } else {
        Err(std::io::Error::new(
            std::io::ErrorKind::Other,
            "Ninja build failed",
        ))
    }
}
